#!/usr/bin/env python3
"""Place generated VO clips on the promo timeline.

    python place.py takes/af_heart            # -> ../js/vo.js, <voice dir>/captions.srt

Each line starts so that its anchor word (or first word) lands on `at`. Word
times come from Kokoro's duration predictor when available, else from Whisper.
The resulting js/vo.js drives both the mixer (music.js) and word-synced visuals.
"""
import json, pathlib, re, shutil, sys
import numpy as np, soundfile as sf

HERE = pathlib.Path(__file__).parent
SR_OUT = 24000


def clean(w):
    return re.sub(r"[^a-z0-9]", '', w.lower())


def srt_time(t):
    ms = int(round(t * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def main():
    src = pathlib.Path(sys.argv[1])
    voice = src.name
    script = json.loads((HERE / 'script.json').read_text())['lines']
    report = json.loads((src / 'report.json').read_text())
    dst = HERE / voice
    dst.mkdir(exist_ok=True)
    clips, warnings, srt = [], [], []
    prev_end = -1
    for line in script:
        r = report[line['id']]
        words = r.get('words') or r.get('asr_words') or []
        words = [w for w in words if clean(w['w'])]
        if not words:
            words = [{'w': line['text'], 's': r['on'], 'e': r['off']}]
        anchor = line.get('anchor')
        a_on = words[0]['s']
        if anchor:
            hit = [w for w in words if clean(w['w']) == clean(anchor)]
            if hit:
                a_on = hit[0]['s']
        # never start before the audible onset (Kokoro adds ~0.1-0.2 s of lead-in)
        t = round(line['at'] - a_on, 3)
        s0, s1 = t + r['on'], t + r['off']
        if s1 > line['end'] + 0.05:
            warnings.append(f"{line['id']}: speech ends {s1:.2f} > limit {line['end']:.2f} (+{s1 - line['end']:.2f}s)")
        if s0 < prev_end + 0.05:
            warnings.append(f"{line['id']}: starts {s0:.2f} before previous line ends {prev_end:.2f}")
        prev_end = s1
        # store as 16-bit PCM (small, lossless enough for speech)
        a, sr = sf.read(src / f"{line['id']}.wav", dtype='float32')
        peak = float(np.max(np.abs(a)))
        if peak > 0.99:
            a = a * (0.99 / peak)
        sf.write(dst / f"{line['id']}.wav", a, sr, subtype='PCM_16')
        clips.append({
            'id': line['id'], 'file': f"vo/{voice}/{line['id']}.wav", 't': t,
            'on': round(s0, 3), 'off': round(s1, 3), 'text': line['text'],
            'words': [{'w': w['w'], 's': round(t + w['s'], 3), 'e': round(t + w['e'], 3)} for w in words],
        })
        srt.append((line['id'], s0, s1, line['text']))
    js = "// Generated by vo/place.py — voice-over clip placement and word timings.\n"
    js += f"const VO = {json.dumps({'voice': voice, 'clips': clips}, indent=1)};\n"
    (HERE.parent / 'js' / 'vo.js').write_text(js)
    # captions: one cue per line (max two lines of 42 chars); short beat lines grouped
    MERGE = [['logo1', 'logo2'], ['no1', 'no2', 'no3', 'no4'], ['outro1', 'outro2']]
    group = {i: g[0] for g in MERGE for i in g}
    cues = []
    for lid, s0, s1, text in srt:
        if cues and group.get(lid) is not None and cues[-1][0] == group.get(lid):
            k = cues[-1]
            cues[-1] = (k[0], k[1], s1, k[3] + ' ' + text)
        else:
            cues.append((group.get(lid, lid), s0, s1, text))

    def wrap(txt, width=42):
        if len(txt) <= width:
            return txt
        words, best = txt.split(), None
        for i in range(1, len(words)):           # most balanced two-line split
            a, b = ' '.join(words[:i]), ' '.join(words[i:])
            if len(a) <= width and len(b) <= width and (best is None or abs(len(a) - len(b)) < best[0]):
                best = (abs(len(a) - len(b)), a + '\n' + b)
        return best[1] if best else txt

    out = []
    for i, (_, a, b, txt) in enumerate(cues):
        end = max(b + 0.25, a + 0.9)                 # linger a little; at least 0.9 s on screen
        if i + 1 < len(cues):
            end = min(end, cues[i + 1][1] - 0.05)    # never overlap the next cue
        out.append(f"{i + 1}\n{srt_time(a)} --> {srt_time(max(end, b))}\n{wrap(txt)}\n")
    out = '\n'.join(out)
    (dst / 'captions.srt').write_text(out)
    print(f"placed {len(clips)} clips for {voice}")
    for w in warnings:
        print('WARN', w)


if __name__ == '__main__':
    main()
